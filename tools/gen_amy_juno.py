"""X0X_AMY: the Juno-60 presets for the FM-1, from tools/amy_k257.json.

    tools/gen_amy_juno.py tools/amy_k257.json build/gen/amy_juno.h

The FM-1 loads a Juno preset as the AMYboard editor does: AMY patch 257 (AMYboard's default, 4 oscs
per voice), then the editor's wire messages that set it up like the Juno patch (amy_k257.json,
written by tools/gen_amy_k257.js from the editor's own code). For each preset this writes its name,
those messages, and the values ui_amy.c's knobs start from, read from the messages. The knobs are
the editor's (its amy_parameters.js), in its units and ui_amy.c's order: what the messages don't
set reads as the editor's amy_default, AMY's value after a reset.
The voice is the editor's: osc 0 the filter and VCA (CTL_OSC), 1 the LFO, 2 Osc A, 3 Osc B.
"""
import json
import re
import sys

NJUNO = 128
NAMES = ["osc a freq", "osc a wave", "osc a duty", "osc a level",
         "osc b freq", "osc b wave", "osc b duty", "osc b level",
         "lfo freq", "lfo osc", "lfo pwm", "lfo filt",
         "vcf freq", "vcf resonance", "vcf kbd", "vcf env",
         "vcf env attack", "vcf env decay", "vcf env sustain", "vcf env release",
         "adsr attack", "adsr decay", "adsr sustain", "adsr release",
         "eq low", "eq mid", "eq high",
         "chorus level", "chorus freq", "chorus depth",
         "reverb level", "reverb live", "reverb damp",
         "echo level", "echo delay", "echo feedback",
         "distortion type", "distortion drive", "distortion mix"]


def field(arg, i, default):
    """field i of a comma list ('179.93,0.677,,5.024'), default when absent or empty"""
    if arg is None:
        return default
    v = arg.split(",")
    return float(v[i]) if i < len(v) and v[i] != "" else default


def parse(wire):
    osc, fx = {}, {}
    for phrase in wire.split("Z"):
        cmds = re.findall(r"([A-Za-z])([-0-9.,]*)", phrase)
        v = None
        for c, a in cmds:
            if c == "v":
                v = int(a)
        for c, a in cmds:
            if c == "v":
                continue
            if v is None:              # no osc: the bus effects (x EQ, k chorus, h reverb, M echo)
                fx[c] = a
            else:
                osc.setdefault(v, {})[c] = a
    o0, o1, o2, o3 = (osc.get(k, {}) for k in range(4))
    return [
        field(o2.get("f"), 0, 440.0), field(o2.get("w"), 0, 0), field(o2.get("d"), 0, 0.5), field(o2.get("a"), 0, 1.0),
        field(o3.get("f"), 0, 440.0), field(o3.get("w"), 0, 0), field(o3.get("d"), 0, 0.5), field(o3.get("a"), 0, 1.0),
        field(o1.get("f"), 0, 4.0), field(o2.get("f"), 5, 0.0), field(o2.get("d"), 5, 0.0), field(o0.get("F"), 5, 0.0),
        field(o0.get("F"), 0, 1000.0), field(o0.get("R"), 0, 0.7), field(o0.get("F"), 1, 0.0), field(o0.get("F"), 4, 0.0),
        field(o0.get("B"), 0, 0.0), field(o0.get("B"), 2, 0.0), field(o0.get("B"), 3, 0.0), field(o0.get("B"), 4, 0.0),
        field(o0.get("A"), 0, 0.0), field(o0.get("A"), 2, 0.0), field(o0.get("A"), 3, 1.0), field(o0.get("A"), 4, 0.0),
        field(fx.get("x"), 0, 0.0), field(fx.get("x"), 1, 0.0), field(fx.get("x"), 2, 0.0),
        field(fx.get("k"), 0, 0.0), field(fx.get("k"), 2, 0.5), field(fx.get("k"), 3, 0.5),
        field(fx.get("h"), 0, 0.0), field(fx.get("h"), 1, 0.85), field(fx.get("h"), 2, 0.5),
        field(fx.get("M"), 0, 0.0), field(fx.get("M"), 1, 500.0), field(fx.get("M"), 3, 0.0),
        0.0, 1.0, 1.0,                 # distortion: no Juno patch sets it (type off, unity drive, all wet)
    ]


def cfloat(x):
    """a C float literal: 0 -> 0.0f, 1355 -> 1355.0f, 1e+05 -> 1e+05f"""
    s = "%g" % x
    return s + ("f" if "." in s or "e" in s else ".0f")


def main(src, dst):
    k257 = json.load(open(src))
    presets = k257["presets"]
    nmsg = max(len(p["messages"]) for p in presets)
    if len(presets) != NJUNO:
        sys.exit(f"gen_amy_juno: {len(presets)} presets in {src}, expected {NJUNO}")
    for p in presets:
        for m in p["messages"]:
            if '"' in m or "\\" in m or len(m) > 200:
                sys.exit(f"gen_amy_juno: {p['name']}: a message the FM-1 can't carry: {m!r}")
    with open(dst, "w") as f:
        f.write(f"/* generated by tools/gen_amy_juno.py from {src.split('/')[-1]}: do not edit */\n")
        f.write(f"/* values: {', '.join(NAMES)} */\n")
        f.write("#define AMY_NJUNO %d\n#define AMY_JUNO_NV %d\n#define AMY_JUNO_NMSG %d\n" % (NJUNO, len(NAMES), nmsg))
        f.write("#define AMY_JUNO_BASE \"%s\"    /* patch %d on synth %d, then the messages (i%d + each) */\n"
                % (k257["base_message"], k257["base_patch"], k257["synth"], k257["synth"]))
        f.write("static const struct { const char *name; float v[AMY_JUNO_NV]; const char *msg[AMY_JUNO_NMSG]; }"
                " AMY_JUNO[AMY_NJUNO] = {\n")
        for p in presets:
            vals = ", ".join(cfloat(x) for x in parse("".join(p["messages"])))
            msgs = ", ".join('"%s"' % m for m in p["messages"])
            f.write('    {"%s", {%s},\n     {%s}},\n' % (p["name"].replace('"', ""), vals, msgs))
        f.write("};\n")


if __name__ == "__main__":
    main(*sys.argv[1:3])
